package com.orivone.dbupgrade.core.dialect.impl;

import java.util.Collections;

import com.orivone.dbupgrade.core.dialect.DbType;
import com.orivone.dbupgrade.core.dialect.UpgradeDialect;
import com.orivone.dbupgrade.core.IdentifierUtils;
import com.orivone.dbupgrade.core.schema.impl.PostgresqlSchemaMetadata;
import com.orivone.dbupgrade.core.schema.SchemaMetadata;
import com.orivone.dbupgrade.core.jdbc.JdbcExecutor;

import java.util.ArrayList;
import java.util.List;

/**
 * PostgreSQL 方言，人大金仓、openGauss、GaussDB 这些 PG 衍生库同样适用。
 * <p>
 * 和 MySQL 基准的差别基本只在类型写法：
 * <ul>
 *     <li>没有 ENGINE / CHARSET / 列注释，字符集由库或 schema 决定</li>
 *     <li>没有 TINYINT，布尔位用 SMALLINT；时间统一 TIMESTAMP</li>
 *     <li>自增主键用 GENERATED BY DEFAULT AS IDENTITY（PG 10+），索引单独建</li>
 *     <li>约束名上限 63 字符，由 {@link IdentifierUtils#buildName} 截断</li>
 * </ul>
 * 字段与约束和基准一致：版本表按 group_code 唯一，记录表按 (changeset_id, group_code) 联合唯一。
 * @author orivone
 */
public class PostgreSqlDialect implements UpgradeDialect {

    /**
     * PostgreSQL 标识符上限 63 字符
     */
    private static final int MAX_IDENTIFIER = 63;

    @Override
    public DbType dbType() {
        return DbType.POSTGRESQL;
    }

    @Override
    public List<String> versionTableDdl(String table) {
        return Collections.singletonList("CREATE TABLE IF NOT EXISTS " + table + " ("
                + " id VARCHAR(40) NOT NULL,"
                + " version VARCHAR(32) NOT NULL,"
                + " updated_by VARCHAR(128),"
                + " updated_at TIMESTAMP,"
                + " group_code VARCHAR(80) NOT NULL DEFAULT 'system',"
                + " CONSTRAINT " + IdentifierUtils.buildName("pk", table, "id", MAX_IDENTIFIER) + " PRIMARY KEY (id),"
                + " CONSTRAINT " + IdentifierUtils.buildName("uk", table, "group_code", MAX_IDENTIFIER)
                + " UNIQUE (group_code)"
                + ")");
    }

    @Override
    public List<String> recordTableDdl(String table) {
        List<String> ddl = new ArrayList<>(3);
        ddl.add("CREATE TABLE IF NOT EXISTS " + table + " ("
                + " id BIGINT GENERATED BY DEFAULT AS IDENTITY,"
                + " changeset_id VARCHAR(255) NOT NULL,"
                + " file_path VARCHAR(512) NOT NULL,"
                + " version VARCHAR(32) NOT NULL,"
                + " checksum VARCHAR(64),"
                + " run_always SMALLINT NOT NULL DEFAULT 0,"
                + " status VARCHAR(16) NOT NULL,"
                + " executed_by VARCHAR(128),"
                + " start_time TIMESTAMP,"
                + " end_time TIMESTAMP,"
                + " error_msg TEXT,"
                + " group_code VARCHAR(80) NOT NULL DEFAULT 'system',"
                + " CONSTRAINT " + IdentifierUtils.buildName("pk", table, "id", MAX_IDENTIFIER) + " PRIMARY KEY (id),"
                + " CONSTRAINT " + IdentifierUtils.buildName("uk", table, "changeset_group", MAX_IDENTIFIER)
                + " UNIQUE (changeset_id, group_code)"
                + ")");
        ddl.add("CREATE INDEX IF NOT EXISTS " + IdentifierUtils.buildName("idx", table, "status", MAX_IDENTIFIER)
                + " ON " + table + " (status)");
        ddl.add("CREATE INDEX IF NOT EXISTS " + IdentifierUtils.buildName("idx", table, "version", MAX_IDENTIFIER)
                + " ON " + table + " (version)");
        return ddl;
    }

    @Override
    public boolean supportsHashComment() {
        return false;
    }

    @Override
    public SchemaMetadata newSchemaMetadata(JdbcExecutor jdbcExecutor) {
        return new PostgresqlSchemaMetadata(jdbcExecutor);
    }
}
